# test creating unique row names
x_test <- c(
  "100111100001001011100000011010100111110001010101111111110011111",
  "100111100001001011100000011010100111110001010101111111110011110",
  "10011110000100101110000001101010011111000101010111111111001111",
  "1001111000010010111000000110101001111100010101011111111100111",
  "1001111000010010111000000110101001111100010101011111111100",
  "10011110000100101110000001101010011111000101010111111",
  "10011110000100101110000001101010011111000101010111110"
)

rn_test_2 <- bit64::as.integer64(unlist(lapply(x_test, strtoi_2)))
# row.names are not unique
identical(length(rn_test_2), length(unique(rn_test_2)))

rn_test_3 <- as.vector(sapply(x_test, strtoi_3))
# row.names are unique
identical(length(rn_test_3), length(unique(rn_test_3)))


